use async_imap::imap_proto::{Response, ResponseCode, Status, UidSetMember};
use futures::StreamExt;
use tokio::io::AsyncWriteExt;

use super::{
    connection::{connect, map_imap_error},
    error::ImapError,
    types::{DraftSyncRequest, DraftSyncResult, ImapCredentials},
};

/// APPEND a replacement before removing precisely identified old versions.
/// Never use a mailbox-wide EXPUNGE: it can delete unrelated messages.
pub(crate) async fn sync(
    creds: &ImapCredentials,
    request: &DraftSyncRequest,
) -> Result<DraftSyncResult, ImapError> {
    let mut session = connect(creds).await?;
    let mailbox = session
        .select(&request.folder)
        .await
        .map_err(map_imap_error)?;
    let validity = mailbox
        .uid_validity
        .ok_or_else(|| ImapError::ProtocolError("Missing UIDVALIDITY".into()))?;
    if request
        .uid_validity
        .is_some_and(|expected| expected != validity)
    {
        return Err(ImapError::ProtocolError(
            "Draft mailbox changed; reopen the server draft before saving or deleting it".into(),
        ));
    }
    // The marker is generated by this application, never supplied as an IMAP query.
    let query = format!("HEADER Message-ID \"{}\"", request.message_id);
    let mut old = session.uid_search(&query).await.map_err(map_imap_error)?;
    if let Some(uid) = request.uid {
        old.insert(uid);
    }
    if (request.content.is_some() || !old.is_empty())
        && !session
            .capabilities()
            .await
            .map_err(map_imap_error)?
            .has_str("UIDPLUS")
    {
        return Err(ImapError::ProtocolError(
            "Server does not support safe replacement or deletion of a single draft (UIDPLUS)"
                .into(),
        ));
    }
    let uid = if let Some(content) = &request.content {
        let appended = append_with_uid(&mut session, &request.folder, content, validity).await?;
        Some(match appended {
            Some(uid) => uid,
            None => {
                let found = session.uid_search(&query).await.map_err(map_imap_error)?;
                found.difference(&old).copied().max().ok_or_else(|| {
                    ImapError::ProtocolError(
                        "Saved draft could not be located; original draft was retained".into(),
                    )
                })?
            }
        })
    } else {
        None
    };
    if !old.is_empty() {
        let set = old.iter().map(u32::to_string).collect::<Vec<_>>().join(",");
        {
            let mut stream = session
                .uid_store(&set, "+FLAGS (\\Deleted)")
                .await
                .map_err(map_imap_error)?;
            while let Some(result) = stream.next().await {
                result.map_err(map_imap_error)?;
            }
        }
        {
            let stream = session.uid_expunge(&set).await.map_err(map_imap_error)?;
            let mut stream = std::pin::pin!(stream);
            while let Some(result) = stream.next().await {
                result.map_err(map_imap_error)?;
            }
        }
    }
    let _ = session.logout().await;
    Ok(DraftSyncResult {
        uid_validity: validity,
        uid,
        removed_uids: old.into_iter().collect(),
    })
}

/// async-imap's APPEND helper discards APPENDUID. Read the tagged completion
/// ourselves so locating a successful save never depends on search indexing.
async fn append_with_uid(
    session: &mut async_imap::Session<super::connection::ImapStream>,
    folder: &str,
    content: &[u8],
    validity: u32,
) -> Result<Option<u32>, ImapError> {
    if folder.contains(['\r', '\n', '\0']) {
        return Err(ImapError::ProtocolError("Invalid draft folder".into()));
    }
    let folder = folder.replace('\\', "\\\\").replace('"', "\\\"");
    let tag = session
        .run_command(format!(
            "APPEND \"{folder}\" (\\Draft \\Seen) {{{}}}",
            content.len()
        ))
        .await
        .map_err(map_imap_error)?;
    let mut sent = false;
    while let Some(response) = session.read_response().await {
        let response = response.map_err(|e| ImapError::ConnectionFailed(e.to_string()))?;
        match response.parsed() {
            Response::Continue { .. } if !sent => {
                let stream = session.as_mut();
                stream
                    .write_all(content)
                    .await
                    .map_err(|e| ImapError::ConnectionFailed(e.to_string()))?;
                stream
                    .write_all(b"\r\n")
                    .await
                    .map_err(|e| ImapError::ConnectionFailed(e.to_string()))?;
                stream
                    .flush()
                    .await
                    .map_err(|e| ImapError::ConnectionFailed(e.to_string()))?;
                sent = true;
            }
            Response::Done {
                tag: response_tag,
                status,
                code,
                ..
            } if response_tag == &tag => {
                if *status != Status::Ok || !sent {
                    return Err(ImapError::ProtocolError(
                        "Server rejected draft APPEND".into(),
                    ));
                }
                return match code {
                    Some(ResponseCode::AppendUid(epoch, uids)) if *epoch == validity => {
                        match uids.as_slice() {
                            [UidSetMember::Uid(uid)] if *uid > 0 => Ok(Some(*uid)),
                            _ => Err(ImapError::ProtocolError("Invalid draft APPENDUID".into())),
                        }
                    }
                    Some(ResponseCode::AppendUid(..)) => Err(ImapError::ProtocolError(
                        "Draft mailbox changed during APPEND; original retained".into(),
                    )),
                    _ => Ok(None),
                };
            }
            Response::Data {
                status: Status::Bye,
                ..
            } => break,
            _ => {}
        }
    }
    Err(ImapError::ConnectionFailed(
        "Connection lost during draft APPEND".into(),
    ))
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::{
        collections::HashSet,
        sync::{Arc, Mutex},
    };
    use tokio::{
        io::{AsyncBufReadExt, AsyncReadExt, AsyncWriteExt, BufReader},
        net::TcpListener,
    };

    #[derive(Default)]
    struct Mailbox {
        drafts: HashSet<u32>,
        next_uid: u32,
        commands: Vec<String>,
        search_empty: bool,
    }

    async fn server(
        uidplus: bool,
        reject_append: bool,
    ) -> (
        ImapCredentials,
        Arc<Mutex<Mailbox>>,
        tokio::task::JoinHandle<()>,
    ) {
        let listener = TcpListener::bind("127.0.0.1:0").await.unwrap();
        let port = listener.local_addr().unwrap().port();
        let state = Arc::new(Mutex::new(Mailbox {
            drafts: HashSet::from([7]),
            next_uid: 8,
            commands: Vec::new(),
            search_empty: false,
        }));
        let shared = state.clone();
        let task = tokio::spawn(async move {
            loop {
                let (stream, _) = listener.accept().await.unwrap();
                let state = shared.clone();
                tokio::spawn(async move {
                    let (reader, mut writer) = stream.into_split();
                    let mut reader = BufReader::new(reader);
                    writer
                        .write_all(b"* OK Test server ready\r\n")
                        .await
                        .unwrap();
                    loop {
                        let mut line = String::new();
                        if reader.read_line(&mut line).await.unwrap() == 0 {
                            break;
                        }
                        let (tag, command) = line.trim_end().split_once(' ').unwrap();
                        let reply = if command.starts_with("LOGIN ") {
                            format!("{tag} OK Logged in\r\n")
                        } else if command.starts_with("SELECT ") {
                            format!(
                                "* 3 EXISTS\r\n* OK [UIDVALIDITY 42] Stable mailbox\r\n{tag} OK [READ-WRITE] Selected\r\n"
                            )
                        } else if command == "CAPABILITY" {
                            format!(
                                "* CAPABILITY IMAP4rev1 {}\r\n{tag} OK Capabilities\r\n",
                                if uidplus { "UIDPLUS" } else { "" }
                            )
                        } else if command.starts_with("UID SEARCH ") {
                            let mailbox = state.lock().unwrap();
                            let ids = mailbox
                                .drafts
                                .iter()
                                .filter(|_| !mailbox.search_empty)
                                .map(u32::to_string)
                                .collect::<Vec<_>>()
                                .join(" ");
                            format!("* SEARCH {ids}\r\n{tag} OK Search\r\n")
                        } else if command.starts_with("APPEND ") {
                            if reject_append {
                                format!("{tag} NO Quota exceeded\r\n")
                            } else {
                                let length: usize = command
                                    .rsplit_once('{')
                                    .unwrap()
                                    .1
                                    .trim_end_matches('}')
                                    .parse()
                                    .unwrap();
                                writer.write_all(b"+ Continue\r\n").await.unwrap();
                                let mut content = vec![0; length];
                                reader.read_exact(&mut content).await.unwrap();
                                let mut newline = String::new();
                                reader.read_line(&mut newline).await.unwrap();
                                let mut mailbox = state.lock().unwrap();
                                let uid = mailbox.next_uid;
                                mailbox.next_uid += 1;
                                mailbox.drafts.insert(uid);
                                format!("* 3 EXISTS\r\n{tag} OK [APPENDUID 42 {uid}] Appended\r\n")
                            }
                        } else if command.starts_with("UID STORE ") {
                            format!("{tag} OK Stored\r\n")
                        } else if let Some(ids) = command.strip_prefix("UID EXPUNGE ") {
                            let mut mailbox = state.lock().unwrap();
                            for id in ids.split(',') {
                                mailbox.drafts.remove(&id.parse::<u32>().unwrap());
                            }
                            format!("{tag} OK Expunged\r\n")
                        } else if command == "LOGOUT" {
                            format!("* BYE Closing\r\n{tag} OK Logout\r\n")
                        } else {
                            panic!("Unexpected IMAP command: {command}")
                        };
                        state.lock().unwrap().commands.push(command.to_string());
                        writer.write_all(reply.as_bytes()).await.unwrap();
                        if command == "LOGOUT" {
                            break;
                        }
                    }
                });
            }
        });
        (
            ImapCredentials {
                host: "127.0.0.1".into(),
                port,
                tls: false,
                email: "test@example.com".into(),
                password: "test".into(),
            },
            state,
            task,
        )
    }

    fn request(content: bool) -> DraftSyncRequest {
        DraftSyncRequest {
            folder: "Drafts".into(),
            uid_validity: Some(42),
            uid: Some(7),
            message_id: "<stable@draft.peps-mail.invalid>".into(),
            content: content
                .then(|| b"Message-ID: <stable@draft.peps-mail.invalid>\r\n\r\nDraft".to_vec()),
        }
    }

    #[tokio::test]
    async fn replaces_then_discards_only_the_identified_draft_over_imap() {
        let (creds, state, task) = server(true, false).await;
        let result = tokio::time::timeout(
            std::time::Duration::from_secs(5),
            sync(&creds, &request(true)),
        )
        .await
        .unwrap()
        .unwrap();
        assert_eq!(result.uid, Some(8));
        assert_eq!(state.lock().unwrap().drafts, HashSet::from([8]));
        let mut discard = request(false);
        discard.uid = Some(8);
        sync(&creds, &discard).await.unwrap();
        let mailbox = state.lock().unwrap();
        assert!(mailbox.drafts.is_empty());
        assert!(mailbox.commands.iter().any(|c| c == "UID EXPUNGE 7"));
        assert!(mailbox.commands.iter().any(|c| c == "UID EXPUNGE 8"));
        assert!(!mailbox.commands.iter().any(|c| c == "EXPUNGE"));
        task.abort();
    }

    #[tokio::test]
    async fn saves_and_deletes_using_appenduid_when_search_cannot_find_saved_messages() {
        let (creds, state, task) = server(true, false).await;
        state.lock().unwrap().search_empty = true;
        let mut request = request(true);
        for expected in [8, 9] {
            let result = sync(&creds, &request).await.unwrap();
            assert_eq!(result.uid, Some(expected));
            assert_eq!(state.lock().unwrap().drafts, HashSet::from([expected]));
            request.uid = result.uid;
        }
        request.content = None;
        sync(&creds, &request).await.unwrap();
        assert!(state.lock().unwrap().drafts.is_empty());
        task.abort();
    }

    #[tokio::test]
    async fn refused_append_or_missing_uidplus_preserves_the_original() {
        for (uidplus, reject_append) in [(true, true), (false, false)] {
            let (creds, state, task) = server(uidplus, reject_append).await;
            assert!(sync(&creds, &request(true)).await.is_err());
            let mailbox = state.lock().unwrap();
            assert_eq!(mailbox.drafts, HashSet::from([7]));
            assert!(
                !mailbox
                    .commands
                    .iter()
                    .any(|c| c.starts_with("UID STORE") || c.contains("EXPUNGE"))
            );
            task.abort();
        }
    }

    #[tokio::test]
    async fn changed_mailbox_identity_prevents_any_deletion() {
        let (creds, state, task) = server(true, false).await;
        let mut request = request(false);
        request.uid_validity = Some(99);
        assert!(sync(&creds, &request).await.is_err());
        assert_eq!(state.lock().unwrap().drafts, HashSet::from([7]));
        task.abort();
    }
}
